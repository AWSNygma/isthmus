import Foundation
import AppKit
import ImageIO
import UniformTypeIdentifiers

/// Creates small `.app` bundles that launch one game through Isthmus, so
/// games appear in Launchpad, Spotlight and the Dock like native apps.
public struct ShortcutMaker: Sendable {
    public var folder: URL
    /// The `isthmus` CLI the shortcut calls (inside the installed app).
    public var cli: URL

    public init(folder: URL = ShortcutMaker.defaultFolder, cli: URL) {
        self.folder = folder; self.cli = cli
    }

    public static var defaultFolder: URL {
        FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Applications/Isthmus Games", isDirectory: true)
    }

    @discardableResult
    public func create(for game: Game, in bottle: Bottle) throws -> URL {
        let fm = FileManager.default
        try fm.createDirectory(at: folder, withIntermediateDirectories: true)
        let safeName = game.name.replacingOccurrences(of: "/", with: "-").replacingOccurrences(of: ":", with: "-")
        let app = folder.appendingPathComponent("\(safeName).app", isDirectory: true)
        if fm.fileExists(atPath: app.path) { try fm.removeItem(at: app) }
        let contents = app.appendingPathComponent("Contents")
        let macos = contents.appendingPathComponent("MacOS")
        let resources = contents.appendingPathComponent("Resources")
        try fm.createDirectory(at: macos, withIntermediateDirectories: true)
        try fm.createDirectory(at: resources, withIntermediateDirectories: true)

        var hasIcon = false
        if let icon = Self.icon(for: game) {
            hasIcon = (try? Self.writeICNS(icon, to: resources.appendingPathComponent("AppIcon.icns"))) != nil
        }

        let plist: [String: Any] = [
            "CFBundleName": game.name,
            "CFBundleDisplayName": game.name,
            "CFBundleIdentifier": "io.github.awsnygma.isthmus.game.\(game.bottleID.slug).\(game.storeID.slug.prefix(40))",
            "CFBundleExecutable": "launch",
            "CFBundlePackageType": "APPL",
            "CFBundleShortVersionString": "1.0",
            "CFBundleIconFile": hasIcon ? "AppIcon" : "",
            "LSUIElement": true,   // the stub exits immediately; the game's own window takes the Dock
            "LSApplicationCategoryType": "public.app-category.games",
            "IsthmusGameID": game.id,
        ]
        let data = try PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0)
        try data.write(to: contents.appendingPathComponent("Info.plist"))

        let script = """
        #!/bin/sh
        # Generated by Isthmus. Launches "\(game.name.replacingOccurrences(of: "\"", with: ""))" in bottle "\(bottle.name.replacingOccurrences(of: "\"", with: ""))".
        CLI=\(shellQuote(cli.path))
        if [ ! -x "$CLI" ]; then
          APP=$(/usr/bin/mdfind "kMDItemCFBundleIdentifier == 'io.github.awsnygma.isthmus'" | /usr/bin/head -n 1)
          CLI="$APP/Contents/Helpers/isthmus"
        fi
        exec "$CLI" play --bottle \(shellQuote(bottle.id)) --game \(shellQuote(game.id)) --detach
        """
        let launcher = macos.appendingPathComponent("launch")
        try script.write(to: launcher, atomically: true, encoding: .utf8)
        try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: launcher.path)
        _ = try? Shell.run("/usr/bin/codesign", ["--force", "--sign", "-", app.path], allowFailure: true)
        NSWorkspace.shared.noteFileSystemChanged(app.path)
        return app
    }

    /// Icon from the executable's resources, else the Steam cover art.
    public static func icon(for game: Game) -> NSImage? {
        if let exe = game.executable, let pe = try? PEFile(url: exe), let ico = pe.iconData(),
           let image = NSImage(data: ico), image.isValid {
            return image
        }
        if let art = game.artwork, let image = NSImage(contentsOf: art) { return squareCrop(image) }
        return nil
    }

    static func squareCrop(_ image: NSImage) -> NSImage {
        let s = min(image.size.width, image.size.height)
        let out = NSImage(size: NSSize(width: s, height: s))
        out.lockFocus()
        image.draw(in: NSRect(x: 0, y: 0, width: s, height: s),
                   from: NSRect(x: (image.size.width - s) / 2, y: (image.size.height - s) / 2, width: s, height: s),
                   operation: .copy, fraction: 1)
        out.unlockFocus()
        return out
    }

    public static func writeICNS(_ image: NSImage, to url: URL) throws {
        guard let dest = CGImageDestinationCreateWithURL(url as CFURL, UTType.icns.identifier as CFString, 6, nil) else {
            throw IsthmusError.unsupported("ICNS encoding unavailable")
        }
        for size in [16, 32, 64, 128, 256, 512] {
            guard let cg = render(image, size: size) else { continue }
            CGImageDestinationAddImage(dest, cg, nil)
        }
        guard CGImageDestinationFinalize(dest) else { throw IsthmusError.unsupported("ICNS write failed") }
    }

    static func render(_ image: NSImage, size: Int) -> CGImage? {
        guard let ctx = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.interpolationQuality = .high
        // Pick the closest representation so small ICO frames stay crisp.
        var rect = NSRect(x: 0, y: 0, width: size, height: size)
        guard let cg = image.cgImage(forProposedRect: &rect, context: nil, hints: nil) else { return nil }
        ctx.draw(cg, in: CGRect(x: 0, y: 0, width: size, height: size))
        return ctx.makeImage()
    }

    private func shellQuote(_ s: String) -> String { "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'" }
}
